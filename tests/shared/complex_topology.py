def signature(node: NodeId, prefix: str) -> str:
    return f"{node.vhost.removeprefix(prefix + '.')}/{node.kind.value}/{node.name}"


def _cycles(cycles: Iterable[Cycle], prefix: str) -> Counter[PathSignature]:
    return Counter(_canonical(tuple(signature(node, prefix) for node in cycle.nodes)) for cycle in cycles)


def check_cycles(auditor: ClusterAuditor, prefix: str) -> None:
    report = auditor.audit()
    expected = Counter(_canonical(path) for path in (*STRUCTURAL_ONLY, *REPUBLISHING))
    candidates = Counter(_canonical(path) for path in REPUBLISHING)
    assert _cycles(report.structural_cycles.cycles, prefix) == expected
    assert _cycles(report.message_loop_candidates.cycles, prefix) == candidates
    assert not report.structural_cycles.truncated
    assert not report.message_loop_candidates.truncated
    assert max(map(len, report.structural_cycles.cycles)) == 11
    assert all(len(path) <= 20 for path in expected)

    # Every cyclic SCC in this design contains exactly one elementary cycle.
    cyclic = auditor.cyclic_components()
    assert len(cyclic) == len(expected)
    assert {frozenset(signature(node, prefix) for node in component.nodes) for component in cyclic} == {
        frozenset(path) for path in expected
    }
    components = auditor.strongly_connected_components()
    assert all(len(component.nodes) == 1 for component in components if not component.is_cyclic)
    partition = [node for component in components for node in component.nodes]
    assert len(partition) == len(set(partition))
    assert set(partition) == auditor.topology.all_node_ids

    for limit in (0, 1, 2, 6, 10, 11):
        limited = auditor.audit(max_cycles=limit)
        for method, reference in (("structural_cycles", expected), ("message_loop_candidates", candidates)):
            result = getattr(limited, method)
            assert result == getattr(auditor, method)(max_cycles=limit)
            assert len(result.cycles) == (min(limit, len(reference)) if limit else len(reference))
            assert result.truncated is (bool(limit) and len(reference) > limit)
            assert _cycles(result.cycles, prefix) <= reference


def check_resources_and_routes(auditor: ClusterAuditor, prefix: str) -> None:
    topology = auditor.topology
    scoped = {node for node in topology.all_node_ids if node.vhost.startswith(prefix + ".")}
    assert Counter(node.kind for node in scoped) == {NodeKind.EXCHANGE: 54, NodeKind.QUEUE: 46, NodeKind.SHOVEL: 13}
    assert len(topology.edges) == 100
    assert {node.cluster_id for node in scoped} == {auditor.cluster_id}
    assert {exchange.exchange_type for exchange in topology.exchanges} == {"direct", "topic", "headers", "fanout"}
    assert {queue.queue_type for queue in topology.queues} == {"classic", "quorum", "stream"}
    edges = {(signature(edge.source, prefix), signature(edge.target, prefix)) for edge in topology.edges}
    healthy_paths = (
        (
            "routing/exchange/route.direct",
            "routing/exchange/route.topic",
            "routing/exchange/route.headers",
            "routing/exchange/route.fanout",
            "routing/queue/route.quorum",
        ),
        (
            "fallback/exchange/fallback.primary",
            "fallback/exchange/fallback.topic",
            "fallback/exchange/fallback.parking",
            "fallback/queue/fallback.plq",
        ),
        (
            "deadletter/exchange/retry.in",
            "deadletter/queue/retry.wait",
            "deadletter/exchange/work.in",
            "deadletter/queue/work.quorum",
            "deadletter/exchange/poison.dlx",
            "deadletter/queue/poison.plq",
        ),
        (
            "region-a/exchange/pipeline.in",
            "region-a/queue/pipeline.q",
            "control/shovel/pipeline.ab",
            "region-b/exchange/pipeline.in",
            "region-b/queue/pipeline.q",
            "control/shovel/pipeline.bc",
            "region-c/exchange/pipeline.in",
            "region-c/queue/pipeline.q",
        ),
    )
    for path in healthy_paths:
        assert len(path) - 1 <= 20
        assert all(pair in edges for pair in pairwise(path))

    parallel = [
        edge for edge in topology.edges if edge.source.name == "route.topic" and edge.target.name == "route.headers"
    ]
    assert {edge.routing_key for edge in parallel} == {"orders.#", "orders.*.created"}
    headers = [edge for edge in topology.edges if edge.source.name == "route.headers"]
    assert len(headers) == 5
    assert {edge.target.name: json.loads(edge.arguments or "{}") for edge in headers} == {
        "route.fanout": {"x-match": "all", "format": "json", "region": "eu"},
        **{
            f"headers.{mode}": {"x-match": mode, "format": "json", "x-demo": "yes"}
            for mode in ("all", "any", "all-with-x", "any-with-x")
        },
    }
    assert {edge.kind for edge in topology.edges} == set(EdgeKind)


def check_policies(auditor: ClusterAuditor, prefix: str) -> None:
    edges = [edge for edge in auditor.topology.edges if edge.source.vhost == prefix + ".policies"]
    assert {
        (edge.source.name, edge.target.name, edge.routing_key) for edge in edges if edge.kind == EdgeKind.DEAD_LETTER
    } == {
        ("policy.work", "policy.dlx", "poison"),
        ("policy.override", "argument.dlx", "poison"),
    }
    assert {(edge.source.name, edge.target.name) for edge in edges if edge.kind == EdgeKind.ALTERNATE_EXCHANGE} == {
        ("policy.primary", "policy.fallback"),
        ("policy.override.exchange", "argument.fallback"),
    }
    default = next(queue for queue in auditor.topology.queues if queue.id.name == "policy.default-type")
    assert default.queue_type == "quorum"
    assert default.replication_factor == 1


def check_degree_findings(auditor: ClusterAuditor, prefix: str) -> None:
    report = auditor.audit()
    assert {
        signature(node.id, prefix) for node in report.black_hole_exchanges if node.id.vhost.startswith(prefix + ".")
    } == {
        "diagnostics/exchange/diag.blackhole",
        "diagnostics/exchange/diag.empty-fanout",
    }
    assert report.unreachable_internal_exchanges == ()
    assert {signature(node.id, prefix) for node in report.queues_without_declared_ingress} == {
        "diagnostics/queue/diag.orphan"
    }
    assert {
        (signature(edge.source, prefix), signature(edge.target, prefix), edge.kind) for edge in report.dangling_edges
    } == {
        ("diagnostics/exchange/diag.missing-ae", "diagnostics/exchange/missing.alternate", EdgeKind.ALTERNATE_EXCHANGE),
        ("diagnostics/queue/diag.missing-dlx", "diagnostics/exchange/missing.dlx", EdgeKind.DEAD_LETTER),
    }


def check_shovels(auditor: ClusterAuditor, prefix: str) -> None:
    report = auditor.audit()
    assert {shovel.id.name for shovel in report.cross_vhost_shovels} == {
        "pipeline.ab",
        "pipeline.bc",
        "shovel2.ab",
        "shovel2.ba",
        "shovel3.ab",
        "shovel3.bc",
        "shovel3.ca",
        "complex.ab",
        "complex.ba",
        "compete.ab",
        "compete.ac",
        "alias.unconfirmed",
    }
    assert {shovel.id.name for shovel in report.shovels_with_unconfirmed_endpoints} == {
        "alias.unconfirmed",
        "uncertain.failover",
    }
    assert {shovel.id.name for shovel in report.shovels_with_unresolved_vhost} == {"uncertain.failover"}
    (group,) = report.competing_shovel_consumers
    assert signature(group.queue, prefix) == "region-a/queue/compete.source"
    assert {signature(shovel.id, prefix) for shovel in group.shovels} == {
        "control/shovel/compete.ab",
        "region-c/shovel/compete.ac",
    }
    alias = next(shovel for shovel in auditor.topology.shovels if shovel.id.name == "alias.unconfirmed")
    assert not alias.source.is_confirmed_local and alias.destination.is_confirmed_local
    assert not any(edge.target == alias.id for edge in auditor.topology.edges)


def check_fanout(auditor: ClusterAuditor, prefix: str) -> None:
    results = auditor.fanout_exchange_bindings()
    assert list(results) == sorted(results, key=lambda group: node_sort_key(group.exchange.id))
    groups = {signature(group.exchange.id, prefix): group for group in results}
    # Explicit scenario expectations: include every empty exchange and every
    # direct target, so omissions and unexpected groups cannot pass spot checks.
    expected: dict[str, dict[str, tuple[str, ...]]] = {
        "routing": {"route.fanout": ("route.classic", "route.quorum", "route.stream")},
        "fallback": {"fallback.parking": ("fallback.plq",)},
        "deadletter": {"poison.dlx": ("poison.plq",)},
        "loops": {
            "binding.self": (),
            "binding.c": (),
            "mixed.b": (),
            "dead.self": ("dead.self.q",),
            "dead.a": ("dead.a.q",),
            "dead.b": ("dead.b.q",),
            "dead-ae.fallback": ("dead-ae.q",),
        },
        "policies": {
            "policy.dlx": ("policy.dlx.q",),
            "argument.dlx": ("argument.dlx.q",),
            "policy.fallback": ("policy.fallback.q",),
            "argument.fallback": ("argument.fallback.q",),
        },
        "region-a": {
            "shovel2.in": ("shovel2.q",),
            "shovel3.in": ("shovel3.q",),
            "complex.work": ("complex.work.q",),
            "complex.dlx": ("complex.forward.q",),
            "compete.in": ("compete.source",),
            "uncertain.in": ("uncertain.source",),
        },
        "region-b": {
            "shovel2.in": ("shovel2.q",),
            "shovel3.in": ("shovel3.q",),
            "complex.fallback": ("complex.work.q",),
            "complex.dlx": ("complex.return.q",),
            "compete.out": ("compete.sink",),
            "uncertain.in": ("uncertain.source",),
            "alias.out": ("alias.sink",),
        },
        "region-c": {"shovel3.in": ("shovel3.q",), "compete.out": ("compete.sink",)},
        "diagnostics": {"diag.empty-fanout": (), "alias.in": ("alias.source",)},
    }
    expected_targets = {
        f"{role}/exchange/{exchange}": targets
        for role, exchanges in expected.items()
        for exchange, targets in exchanges.items()
    }
    assert len(results) == len(groups) == len(expected_targets)
    assert {name: tuple(queue.id.name for queue in group.queues) for name, group in groups.items()} == expected_targets
    for group in results:
        assert list(group.queues) == sorted(group.queues, key=lambda queue: node_sort_key(queue.id))
        for queue in group.queues:
            assert (queue.id.cluster_id, queue.id.vhost) == (group.exchange.id.cluster_id, group.exchange.id.vhost)
            expected_type = {"route.quorum": "quorum", "route.stream": "stream"}.get(queue.id.name, "classic")
            assert queue.queue_type == expected_type
            assert queue.replication_factor == (1 if expected_type == "quorum" else None)
    route = groups["routing/exchange/route.fanout"]
    assert [(queue.id.name, queue.queue_type, queue.replication_factor) for queue in route.queues] == [
        ("route.classic", "classic", None),
        ("route.quorum", "quorum", 1),
        ("route.stream", "stream", None),
    ]
    # Two parallel fanout bindings to route.classic still contribute one target.
    assert (
        len(
            [
                edge
                for edge in auditor.topology.edges
                if edge.source == route.exchange.id and edge.target.name == "route.classic"
            ]
        )
        == 2
    )
    assert auditor.audit().fanout_exchange_bindings == results


